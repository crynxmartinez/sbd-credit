import { z } from "zod";
import { MAX_AMOUNT_CENTS, MIN_REASON_LENGTH, PAYMENT_TERMS, POSTABLE_LEDGER_TYPES } from "./domain/constants";
import { isValidISODate } from "./domain/dates";

/**
 * Every request body is checked here before it reaches a service. The same schemas validate the forms in the browser,
 * but the server never trusts that they ran.
 */

const isoDate = z.string().refine(isValidISODate, "Use a valid date.");

/** Trimmed text that is stored as null when left empty. */
const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Keep this under ${max} characters.`)
    .nullish()
    .transform((value) => (value ? value : null));

const optionalEmail = z
  .string()
  .trim()
  .max(200)
  .nullish()
  .refine((value) => !value || z.email().safeParse(value).success, "Enter a valid email address.")
  .transform((value) => (value ? value : null));

/** Only web links. Anything else (javascript:, data:, file:) is refused. */
const optionalWebUrl = z
  .string()
  .trim()
  .max(500)
  .nullish()
  .refine((value) => {
    if (!value) return true;
    try {
      return ["http:", "https:"].includes(new URL(value).protocol);
    } catch {
      return false;
    }
  }, "Enter a link starting with http:// or https://.")
  .transform((value) => (value ? value : null));

const cents = z.number().int().min(0).max(MAX_AMOUNT_CENTS);
/** Generated by the browser once per form. Lets the server recognise a retry of the same submission. */
const requestKey = z.uuid().optional();
const paymentTerms = z.enum(PAYMENT_TERMS);
const version = z.number().int().min(1);

const profileFields = {
  businessName: z.string().trim().min(1, "Business name is required.").max(200),
  contactName: optionalText(120),
  phone: optionalText(40),
  email: optionalEmail,
  billingAddress: optionalText(300),
  dateApplied: isoDate,
  requestedLimitCents: cents.nullish().transform((value) => value ?? null),
  accountingAppName: optionalText(80),
  accountingProjectUrl: optionalWebUrl,
  notes: optionalText(5000),
};

export const customerCreateSchema = z.object({ ...profileFields, requestKey });

export const customerUpdateSchema = z.object({
  ...profileFields,
  version,
  // Credit terms are only honoured for admins; the service enforces that.
  creditLimitCents: cents.optional(),
  paymentTerms: paymentTerms.optional(),
  creditStartDate: isoDate.nullish(),
});

const reason = z
  .string()
  .trim()
  .max(500)
  .nullish()
  .transform((value) => (value ? value : null));

export const decisionSchema = z.discriminatedUnion("action", [
  z.object({ action: z.literal("start_review"), version }),
  z.object({
    action: z.literal("approve"),
    version,
    creditLimitCents: cents.min(1, "Enter a credit limit greater than 0."),
    paymentTerms,
    creditStartDate: isoDate,
  }),
  z.object({ action: z.literal("deny"), version, reason }),
  z.object({ action: z.literal("suspend"), version, reason }),
  z.object({ action: z.literal("reopen"), version }),
]);

export const ledgerEntrySchema = z
  .object({
    type: z.enum(POSTABLE_LEDGER_TYPES),
    amountCents: z.number().int().min(-MAX_AMOUNT_CENTS).max(MAX_AMOUNT_CENTS),
    entryDate: isoDate,
    dueDate: isoDate.nullish(),
    reference: optionalText(60),
    note: optionalText(500),
    requestKey,
  })
  .superRefine((entry, ctx) => {
    if (entry.type === "ADJUSTMENT" && entry.amountCents === 0) {
      ctx.addIssue({ code: "custom", path: ["amountCents"], message: "An adjustment cannot be zero." });
    }
    if (entry.type !== "ADJUSTMENT" && entry.amountCents <= 0) {
      ctx.addIssue({ code: "custom", path: ["amountCents"], message: "Enter an amount greater than 0." });
    }
    if (entry.dueDate && (entry.type === "PAYMENT" || entry.type === "WRITE_OFF")) {
      ctx.addIssue({ code: "custom", path: ["dueDate"], message: `A ${entry.type === "PAYMENT" ? "payment" : "write-off"} has no due date.` });
    }
    if (entry.type === "WRITE_OFF" && (entry.note ?? "").length < MIN_REASON_LENGTH) {
      ctx.addIssue({ code: "custom", path: ["note"], message: "Say why this is being written off." });
    }
    if (entry.dueDate && entry.dueDate < entry.entryDate) {
      ctx.addIssue({ code: "custom", path: ["dueDate"], message: "The due date cannot be before the entry date." });
    }
  });

export const voidSchema = z.object({
  reason: z.string().trim().min(MIN_REASON_LENGTH, "Say why this entry is being voided.").max(500),
});

export const reversalSchema = z.object({
  reason: z.string().trim().min(MIN_REASON_LENGTH, "Say why this entry is being reversed.").max(500),
  requestKey,
});

export const loginSchema = z.object({
  // A staff username or a customer's email address.
  username: z.string().trim().min(1, "Enter your username or email.").max(200),
  password: z.string().min(1, "Enter your password.").max(200),
});

export type CustomerCreateInput = z.output<typeof customerCreateSchema>;
export type CustomerUpdateInput = z.output<typeof customerUpdateSchema>;
export type DecisionInput = z.output<typeof decisionSchema>;
export type LedgerEntryInput = z.output<typeof ledgerEntrySchema>;
export type ReversalInput = z.output<typeof reversalSchema>;
